"""Smoke tests for AL-JARIDA core flows."""
from datetime import timedelta
from django.test import TestCase
from django.utils import timezone
from django.urls import reverse
from news.models import Article, Category


class ArticleTests(TestCase):
    def setUp(self):
        self.cat = Category.objects.create(name="World", kind=Category.Kind.WORLD)
        self.live = Article.objects.create(
            title="Live Story", body="Para one.\nPara two.", category=self.cat,
            status=Article.Status.PUBLISHED, publish_at=timezone.now() - timedelta(hours=1))
        self.future = Article.objects.create(
            title="Scheduled Story", body="Soon.", category=self.cat,
            status=Article.Status.PUBLISHED, publish_at=timezone.now() + timedelta(days=1))

    def test_published_excludes_future(self):
        titles = list(Article.objects.published().values_list("title", flat=True))
        self.assertIn("Live Story", titles)
        self.assertNotIn("Scheduled Story", titles)

    def test_slug_autogenerated(self):
        self.assertEqual(self.live.slug, "live-story")

    def test_paragraph_split(self):
        self.assertEqual(len(self.live.paragraphs), 2)

    def test_home_renders(self):
        self.assertEqual(self.client.get(reverse("news:home")).status_code, 200)

    def test_future_article_404s_for_public(self):
        r = self.client.get(self.future.get_absolute_url())
        self.assertEqual(r.status_code, 404)

    def test_view_counter_increments(self):
        start = self.live.view_count
        self.client.get(self.live.get_absolute_url())
        self.live.refresh_from_db()
        self.assertEqual(self.live.view_count, start + 1)

    def test_search_api_returns_json(self):
        r = self.client.get(reverse("news:search_api"), {"q": "Live"})
        self.assertEqual(r.status_code, 200)
        self.assertEqual(r.json()["results"][0]["title"], "Live Story")


class TrendingTests(TestCase):
    """The homepage rail ranks by how often a story was actually opened."""

    def setUp(self):
        self.cat = Category.objects.create(name="World", kind=Category.Kind.WORLD)
        # Deliberately published newest-first in the OPPOSITE order to the
        # ranking we expect, so a rail that silently fell back to
        # "-publish_at" would produce the reverse list and fail loudly.
        now = timezone.now()
        self.articles = [
            Article.objects.create(
                title=f"Story {i}", body="Body.", category=self.cat,
                status=Article.Status.PUBLISHED,
                publish_at=now - timedelta(hours=i + 1))
            for i in range(4)
        ]

    def _trending(self):
        return list(self.client.get(reverse("news:home")).context["trending"])

    def test_rail_ranks_by_opens(self):
        # Open Story 3 three times and Story 2 once; nothing else is opened.
        for _ in range(3):
            self.client.get(self.articles[3].get_absolute_url())
        self.client.get(self.articles[2].get_absolute_url())

        # Story 0 is the hero (newest, no is_featured set anywhere), so it
        # is excluded from the rail — the rest rank by open count.
        titles = [a.title for a in self._trending()]
        self.assertEqual(titles[:2], ["Story 3", "Story 2"])

    def test_opening_a_story_moves_it_up_the_rail(self):
        self.client.get(self.articles[3].get_absolute_url())
        self.assertEqual(self._trending()[0].title, "Story 3")

        # A different story overtakes it once it has been opened more.
        for _ in range(2):
            self.client.get(self.articles[1].get_absolute_url())
        self.assertEqual(self._trending()[0].title, "Story 1")


class RelatedTests(TestCase):
    """Related stories render under the article, with a picture each."""

    def setUp(self):
        self.cat = Category.objects.create(name="World", kind=Category.Kind.WORLD)
        self.other = Category.objects.create(name="Sports",
                                             kind=Category.Kind.SPORTS)
        now = timezone.now()
        self.article = Article.objects.create(
            title="Main Story", body="Body.", category=self.cat,
            status=Article.Status.PUBLISHED, publish_at=now - timedelta(hours=1))
        self.same_cat = Article.objects.create(
            title="Sibling Story", body="Body.", category=self.cat,
            status=Article.Status.PUBLISHED, publish_at=now - timedelta(hours=2))

    def test_related_prefers_same_category(self):
        related = self.client.get(self.article.get_absolute_url()).context["related"]
        self.assertEqual(related[0].title, "Sibling Story")

    def test_related_never_includes_the_article_itself(self):
        related = self.client.get(self.article.get_absolute_url()).context["related"]
        self.assertNotIn(self.article.pk, [a.pk for a in related])

    def test_related_tops_up_from_other_categories(self):
        # Only one sibling exists in World, so the row would be short —
        # it fills from elsewhere rather than rendering a gap-toothed grid.
        for i in range(3):
            Article.objects.create(
                title=f"Filler {i}", body="Body.", category=self.other,
                status=Article.Status.PUBLISHED,
                publish_at=timezone.now() - timedelta(hours=5 + i))
        related = self.client.get(self.article.get_absolute_url()).context["related"]
        self.assertEqual(len(related), 3)
        self.assertEqual(len({a.pk for a in related}), 3)

    def test_every_article_has_an_image(self):
        # No upload and no featured_image_url — image_src must still
        # resolve, so no card renders as an empty box.
        self.assertTrue(self.article.image_src.startswith("https://"))

    def test_related_renders_in_the_article_column_not_the_sidebar(self):
        html = self.client.get(self.article.get_absolute_url()).content.decode()
        self.assertIn('class="related"', html)
        # The related block must close before the <aside> opens.
        self.assertLess(html.index('class="related"'), html.index("<aside"))
